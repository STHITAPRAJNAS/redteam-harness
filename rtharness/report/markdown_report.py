"""Markdown report — the human-readable assessment write-up."""
from __future__ import annotations

import datetime as _dt
from typing import List

from ..core.result import Finding, RunResult, Severity

_SEV_ORDER = [Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM, Severity.LOW]
_SEV_EMOJI = {
    Severity.CRITICAL: "🔴", Severity.HIGH: "🟠",
    Severity.MEDIUM: "🟡", Severity.LOW: "🔵", Severity.INFO: "⚪",
}


def _fmt_ts(ts: float) -> str:
    return _dt.datetime.fromtimestamp(ts, _dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")


def _sample_transcript(finding: Finding, max_chars: int = 600) -> str:
    for a in finding.attempts:
        if a.vulnerable:
            lines = []
            for turn in a.sent:
                content = turn["content"].replace("\n", " ")
                if len(content) > 240:
                    content = content[:240] + "…"
                lines.append("  %s: %s" % (turn["role"], content))
            resp = a.response_text.replace("\n", " ")
            if len(resp) > max_chars:
                resp = resp[:max_chars] + "…"
            lines.append("  assistant: %s" % resp)
            return "\n".join(lines)
    return ""


def to_markdown(result: RunResult) -> str:
    out: List[str] = []
    w = out.append

    w("# Red-Team Assessment Report")
    w("")
    w("- **Target:** `%s`" % result.target_name)
    w("- **Attack tier:** %d" % result.tier)
    w("- **Started:** %s" % _fmt_ts(result.started_at))
    w("- **Duration:** %.2fs" % result.duration_s)
    w("- **Probes run:** %d  |  **Attempts:** %d"
      % (len(result.findings), result.total_attempts))
    w("")

    # Executive summary.
    risk = result.risk_score()
    top = result.highest_severity()
    w("## Executive summary")
    w("")
    w("**Risk score: %d/100** — highest confirmed severity: %s %s"
      % (risk, _SEV_EMOJI.get(top, ""), top.label))
    w("")
    counts = result.severity_counts()
    w("| Severity | Confirmed findings |")
    w("|---|---|")
    for sev in _SEV_ORDER:
        w("| %s %s | %d |" % (_SEV_EMOJI[sev], sev.label, counts.get(sev.label, 0)))
    w("")

    vuln = sorted(result.vulnerable_findings,
                  key=lambda f: f.severity, reverse=True)
    if not vuln:
        w("No vulnerabilities were confirmed at this tier. "
          "Consider re-running at a higher tier for deeper coverage.")
        w("")
    else:
        w("### Confirmed findings")
        w("")
        w("| Severity | Finding | OWASP | ATLAS | Hits |")
        w("|---|---|---|---|---|")
        for f in vuln:
            w("| %s %s | %s | %s | %s | %d/%d |" % (
                _SEV_EMOJI[f.severity], f.severity.label, f.title,
                ", ".join(f.owasp) or "-", ", ".join(f.atlas) or "-",
                f.n_vulnerable, f.n_attempts))
        w("")

    # Detailed findings.
    w("## Findings detail")
    w("")
    for f in sorted(result.findings, key=lambda f: (not f.vulnerable, -int(f.severity))):
        status = "VULNERABLE" if f.vulnerable else "not detected"
        emoji = _SEV_EMOJI[f.effective_severity]
        w("### %s `%s` — %s" % (emoji, f.probe_id, f.title))
        w("")
        w("- **Status:** %s (%d/%d attempts fired)"
          % (status, f.n_vulnerable, f.n_attempts))
        w("- **Severity:** %s" % f.severity.label)
        w("- **OWASP:** %s" % (", ".join(f.owasp) or "-"))
        w("- **MITRE ATLAS:** %s" % (", ".join(f.atlas) or "-"))
        w("")
        if f.description:
            w(f.description)
            w("")
        if f.vulnerable:
            w("**Example that fired:**")
            w("")
            w("```")
            w(_sample_transcript(f))
            w("```")
            w("")
        if f.remediation:
            w("**Remediation:** %s" % f.remediation)
            w("")

    w("---")
    w("")
    w("_Generated by rtharness. For authorised security testing only. "
      "Findings are heuristic; confirm manually before acting._")
    return "\n".join(out)


def write_markdown(result: RunResult, path: str) -> str:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(to_markdown(result))
    return path
